import { test, expect } from '@playwright/test';
import {createTestPatient,loginAsTestPatient} from './helpers/testAccount';
const API='http://localhost:3000';

test('real backend: Sri Sai basket survives listing navigation and refresh, updates and removes',async({page,request})=>{
 await page.setViewportSize({width:1536,height:1024});
 let orderRequests=0;page.on('request',r=>{if(new URL(r.url()).pathname==='/orders'&&r.method()==='POST')orderRequests++;});
 console.log('Creating isolated real patient');
 const patient=await createTestPatient(request);
 const headers={Authorization:`Bearer ${patient.token}`};
 console.log('Patient created; reading pharmacies');
 const providers=await request.get(`${API}/patients/providers?service=PHARMACY`,{headers});expect(providers.ok()).toBeTruthy();
 const pharmacy=(await providers.json()).data.find((p:any)=>(p.display_name||p.business_name)==='Sri Sai Medicals');expect(pharmacy).toBeTruthy();
 const catalogue=await request.get(`${API}/medicines/pharmacy-catalogue/${pharmacy.id}`,{headers});expect(catalogue.ok()).toBeTruthy();
 const medicine=(await catalogue.json()).items.find((m:any)=>!m.requires_prescription&&Number(m.mrp)>0&&m.available_quantity>=3);expect(medicine,'Existing OTC medicine with real price/stock is required').toBeTruthy();
 console.log('Real medicine selected; opening browser');
 await loginAsTestPatient(page,patient);
 await page.goto('/pharmacy-orders/new');
 await page.getByRole('searchbox',{name:'Search pharmacies'}).fill('Sri Sai Medicals');
 await page.getByRole('button',{name:'Order from Sri Sai Medicals',exact:true}).click();
 await expect(page.getByText('Loading saved baskets...',{exact:true})).toHaveCount(0);
 const item=page.locator('section[aria-label="Medicine results"] li').filter({hasText:medicine.medicine_name});
 const saved=page.waitForResponse(r=>r.url().includes('/orders/baskets/')&&r.request().method()==='PUT');
 console.log('Catalogue loaded; adding medicine');
 await item.getByRole('button',{name:'Add',exact:true}).click();expect((await saved).ok()).toBeTruthy();
 console.log('Basket saved; checking backend');
 const snapshot=await request.get(`${API}/orders/baskets`,{headers});const basket=(await snapshot.json()).find((b:any)=>b.pharmacyId===pharmacy.id);expect(basket.lines[0].medicine.id).toBe(medicine.id);expect(basket.lines[0].quantity).toBe(1);
 const unauthorized=await request.get(`${API}/orders/baskets`);expect(unauthorized.status()).toBe(401);
 const conflict=await request.put(`${API}/orders/baskets/${pharmacy.id}`,{headers,data:{version:0,items:[]}});expect(conflict.status()).toBe(409);
 await page.goto('/pharmacy-orders/new');
 await expect(page.getByRole('heading',{name:'Your saved order',exact:true})).toBeVisible();
 await expect(page.getByText('Sri Sai Medicals',{exact:true}).first()).toBeVisible();
 await expect(page.getByRole('list',{name:'Pharmacies',exact:true})).toBeVisible();
 await page.screenshot({path:'artifacts/basket-rendering/backend-saved-baskets-listing.png'});
 const preview=page.getByRole('region',{name:'Resume order from Sri Sai Medicals',exact:true});
 await page.setViewportSize({width:390,height:844});await preview.scrollIntoViewIfNeeded();
 await expect.poll(()=>page.locator('aside[aria-label="Main navigation"]').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
 const previewBounds=await preview.boundingBox();expect(previewBounds!.width).toBeLessThanOrEqual(390);
 await preview.screenshot({path:'artifacts/basket-rendering/resume-order-mobile.png'});
 await page.setViewportSize({width:1536,height:1024});
 const resumeCard=page.getByRole('region',{name:'Resume order from Sri Sai Medicals',exact:true});
 await expect(resumeCard).toContainText(medicine.medicine_name);
 await expect(resumeCard).toContainText(`INR ${Number(medicine.mrp).toFixed(2)}`);
 await resumeCard.getByRole('button',{name:'Discard order',exact:true}).click();
 await expect(resumeCard.getByRole('group',{name:'Confirm discard order'})).toBeVisible();
 await resumeCard.getByRole('button',{name:'Keep order',exact:true}).click();
 await resumeCard.getByRole('button',{name:'Resume order',exact:true}).click();
 await page.getByRole('region',{name:'Basket launcher'}).getByRole('button',{name:'View basket'}).click();
 const drawer=page.getByRole('dialog');await expect(drawer.getByText(medicine.medicine_name,{exact:true})).toBeVisible();
 const changed=page.waitForResponse(r=>r.url().includes('/orders/baskets/')&&r.request().method()==='PUT');
 await drawer.getByRole('button',{name:`Increase basket quantity of ${medicine.medicine_name}`}).click();expect((await changed).ok()).toBeTruthy();
 await page.goto(`/pharmacy-orders/new?pharmacy=${pharmacy.id}`);
 await expect(page.getByRole('region',{name:'Basket launcher'})).toContainText('2 units added');
 await page.getByRole('region',{name:'Basket launcher'}).getByRole('button',{name:'View basket'}).click();
 await expect(page.getByRole('dialog').getByText('1 medicine · 2 units',{exact:true})).toBeVisible();
 await page.screenshot({path:'artifacts/basket-rendering/backend-persisted-basket.png'});
 const removed=page.waitForResponse(r=>r.url().includes('/orders/baskets/')&&r.request().method()==='PUT');
 await page.getByRole('dialog').getByRole('button',{name:`Remove ${medicine.medicine_name} from basket`}).click();expect((await removed).ok()).toBeTruthy();
 await page.goto('/pharmacy-orders/new');await expect(page.getByRole('button',{name:'Resume order'})).toHaveCount(0);
 // Verify confirmed discard uses the same backend basket, without creating an order.
 await page.goto(`/pharmacy-orders/new?pharmacy=${pharmacy.id}`);
 const addedAgain=page.waitForResponse(r=>r.url().includes('/orders/baskets/')&&r.request().method()==='PUT');
 await page.locator('section[aria-label="Medicine results"] li').filter({hasText:medicine.medicine_name}).getByRole('button',{name:'Add',exact:true}).click();expect((await addedAgain).ok()).toBeTruthy();
 await page.goto('/pharmacy-orders/new');
 const discardCard=page.getByRole('region',{name:'Resume order from Sri Sai Medicals',exact:true});
 await discardCard.getByRole('button',{name:'Discard order',exact:true}).click();
 const discarded=page.waitForResponse(r=>r.url().includes('/orders/baskets/')&&r.request().method()==='PUT');
 await discardCard.getByRole('button',{name:'Confirm discard',exact:true}).click();expect((await discarded).ok()).toBeTruthy();
 await expect(discardCard).toHaveCount(0);
 const final=await request.get(`${API}/orders/baskets`,{headers});expect((await final.json()).find((b:any)=>b.pharmacyId===pharmacy.id).lines).toEqual([]);expect(orderRequests).toBe(0);
});
